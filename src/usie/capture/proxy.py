"""Per-capture filtering forward proxy: the enforcing SSRF control for browser traffic.

Why: in Playwright 1.56 / Chromium 141, `page.route` is NOT invoked for server redirect hops
(verified by experiment, see docs/DECISIONS.md D-009), so request interception alone cannot stop
a redirect to an internal address. A proxy sees every connection the browser makes (documents,
redirects, subresources, WebSockets), resolves DNS once, validates every address, and connects
to the pinned IP.

Plain-HTTP requests are forwarded with `Connection: close` so one proxied connection carries
one request. Denied connections are recorded in `blocked`. Every response generated by the
proxy itself (policy denial, unreachable upstream, bad request) carries
`X-USIE-Proxy: <reason>` so Layer 1 never mistakes it for an origin response.
"""

from __future__ import annotations

import asyncio
import contextlib
from urllib.parse import urlsplit

from usie.urlsafety import (
    DestinationPolicy,
    Resolver,
    UnsafeDestinationError,
    default_resolver,
    pin_destination,
)

PROXY_HEADER = "x-usie-proxy"
_MAX_HEAD = 64 * 1024
_IO_TIMEOUT = 20.0


class GuardProxy:
    def __init__(self, policy: DestinationPolicy, resolver: Resolver = default_resolver) -> None:
        self.policy = policy
        self.resolver = resolver
        self.blocked: list[str] = []
        self._server: asyncio.Server | None = None
        self._tasks: set[asyncio.Task[None]] = set()

    async def start(self) -> str:
        self._server = await asyncio.start_server(self._on_client, "127.0.0.1", 0)
        port = self._server.sockets[0].getsockname()[1]
        return f"http://127.0.0.1:{port}"

    async def stop(self) -> None:
        if self._server is not None:
            self._server.close()
            await self._server.wait_closed()
        for task in list(self._tasks):
            task.cancel()
        await asyncio.gather(*self._tasks, return_exceptions=True)

    def _on_client(self, reader: asyncio.StreamReader, writer: asyncio.StreamWriter) -> None:
        task = asyncio.ensure_future(self._handle(reader, writer))
        self._tasks.add(task)
        task.add_done_callback(self._tasks.discard)

    @staticmethod
    async def _reply(writer: asyncio.StreamWriter, line: str, reason: str) -> None:
        with contextlib.suppress(ConnectionError, OSError):
            writer.write(
                f"HTTP/1.1 {line}\r\n{PROXY_HEADER}: {reason}\r\n"
                "Content-Length: 0\r\nConnection: close\r\n\r\n".encode()
            )
            await writer.drain()
        writer.close()

    async def _handle(self, reader: asyncio.StreamReader, writer: asyncio.StreamWriter) -> None:
        upstream_writer: asyncio.StreamWriter | None = None
        try:
            try:
                head = await asyncio.wait_for(reader.readuntil(b"\r\n\r\n"), _IO_TIMEOUT)
            except (
                asyncio.IncompleteReadError,
                asyncio.LimitOverrunError,
                TimeoutError,
                ConnectionError,
            ):
                writer.close()
                return
            if len(head) > _MAX_HEAD:
                await self._reply(writer, "431 Request Header Fields Too Large", "bad_request")
                return
            request_line, _, header_block = head.partition(b"\r\n")
            parts = request_line.decode("latin-1").split(" ")
            if len(parts) != 3:
                await self._reply(writer, "400 Bad Request", "bad_request")
                return
            method, target, version = parts
            is_connect = method.upper() == "CONNECT"
            try:
                if is_connect:
                    host, port = self._split_authority(target)
                    origin_target = ""
                else:
                    url = urlsplit(target)
                    if url.scheme.lower() != "http" or not url.hostname:
                        await self._reply(writer, "400 Bad Request", "bad_request")
                        return
                    host, port = url.hostname, url.port or 80
                    origin_target = (url.path or "/") + (f"?{url.query}" if url.query else "")
            except ValueError:
                await self._reply(writer, "400 Bad Request", "bad_request")
                return
            try:
                loop = asyncio.get_running_loop()
                ip = await loop.run_in_executor(
                    None, pin_destination, host, self.policy, self.resolver
                )
            except UnsafeDestinationError as exc:
                self.blocked.append(f"{target[:300]} :: {exc}")
                await self._reply(writer, "403 Forbidden", "blocked")
                return
            except OSError:
                await self._reply(writer, "502 Bad Gateway", "upstream_unreachable")
                return
            try:
                up_reader, upstream_writer = await asyncio.wait_for(
                    asyncio.open_connection(ip, port), _IO_TIMEOUT
                )
            except (OSError, TimeoutError):
                await self._reply(writer, "502 Bad Gateway", "upstream_unreachable")
                return
            assert upstream_writer is not None
            if is_connect:
                writer.write(b"HTTP/1.1 200 Connection Established\r\n\r\n")
                await writer.drain()
            else:
                kept = [
                    ln
                    for ln in header_block.split(b"\r\n")
                    if ln
                    and not ln.lower().startswith(
                        (b"proxy-connection:", b"connection:", b"proxy-authorization:")
                    )
                ]
                new_head = (
                    f"{method} {origin_target} {version}\r\n".encode()
                    + b"\r\n".join(kept)
                    + b"\r\nConnection: close\r\n\r\n"
                )
                upstream_writer.write(new_head)
                await upstream_writer.drain()
            await self._pipe_both(reader, writer, up_reader, upstream_writer)
        except (ConnectionError, asyncio.CancelledError, OSError):
            pass
        finally:
            for w in (writer, upstream_writer):
                if w is not None:
                    with contextlib.suppress(Exception):
                        w.close()

    @staticmethod
    def _split_authority(authority: str) -> tuple[str, int]:
        if authority.startswith("["):
            host, _, rest = authority[1:].partition("]")
            port_text = rest.lstrip(":")
        else:
            host, _, port_text = authority.rpartition(":")
        if not host or not port_text.isdigit() or not 0 < int(port_text) < 65536:
            raise ValueError("bad CONNECT authority")
        return host, int(port_text)

    @staticmethod
    async def _pipe_both(
        r1: asyncio.StreamReader,
        w1: asyncio.StreamWriter,
        r2: asyncio.StreamReader,
        w2: asyncio.StreamWriter,
    ) -> None:
        async def pipe(src: asyncio.StreamReader, dst: asyncio.StreamWriter) -> None:
            while data := await src.read(65536):
                dst.write(data)
                await dst.drain()

        tasks = [asyncio.ensure_future(pipe(r1, w2)), asyncio.ensure_future(pipe(r2, w1))]
        try:
            await asyncio.wait(tasks, return_when=asyncio.FIRST_COMPLETED)
        finally:
            for t in tasks:
                t.cancel()
            await asyncio.gather(*tasks, return_exceptions=True)
